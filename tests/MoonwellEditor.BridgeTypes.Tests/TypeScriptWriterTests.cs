using System.Text.Json;
using System.Text.Json.Serialization.Metadata;

namespace MoonwellEditor.BridgeTypes.Tests;

public sealed class TypeScriptWriterTests
{
    private static readonly JsonSerializerOptions Options = new(JsonSerializerDefaults.Web)
    {
        TypeInfoResolver = new DefaultJsonTypeInfoResolver(),
    };

    private static readonly DocComments Docs = DocComments.Load([typeof(Answer).Assembly]);

    private static string Write(params Type[] others) => Write(new BridgeShape([], [], typeof(SampleCode), others));

    private static string Write(BridgeShape shape) => TypeScriptWriter.Write(shape, Options, Options, Docs);

    private static BridgeShape WithCommands(params CommandShape[] commands) => new(commands, [], typeof(SampleCode), []);

    [Fact]
    public void A_nullable_answer_field_is_or_null()
    {
        var text = Write(typeof(Answer));

        Assert.Contains("  name: string;\n", text);
        Assert.Contains("  title: string | null;\n", text);
    }

    [Fact]
    public void An_argument_with_a_default_may_be_left_out()
    {
        var text = Write(WithCommands(new CommandShape("go", typeof(Args), typeof(string), false, false)));

        Assert.Contains("  level: number;\n", text);
        Assert.Contains("  parent: string | null;\n", text);
        Assert.Contains("  mode?: string;\n", text);
        Assert.Contains("  path?: string | null;\n", text);
    }

    [Fact]
    public void Lists_and_dictionaries()
    {
        var text = Write(typeof(Holder));

        Assert.Contains("  names: string[];\n", text);
        Assert.Contains("  byName: Record<string, number>;\n", text);
        Assert.Contains("  byKind: Partial<Record<CamelKind, number>>;\n", text);
    }

    [Fact]
    public void Enum_text_comes_from_the_serializer()
    {
        var text = Write(typeof(Kinds));

        Assert.Contains("export type PascalKind = \"Unit\" | \"StartLocation\";\n", text);
        Assert.Contains("export type CamelKind = \"unit\" | \"startLocation\";\n", text);
        Assert.Contains("export type PlainKind = 0 | 1;\n", text);
    }

    [Fact]
    public void Docs_are_copied()
    {
        var text = Write(typeof(Documented), typeof(Answer));

        Assert.Contains("/** The `x` of Answer. */\nexport type Documented = {\n", text);
        Assert.Contains("/** An answer. */\nexport type Answer = {\n  /** Its name. */\n  name: string;\n", text);
    }

    [Fact]
    public void The_output_is_stable()
    {
        var first = Write(typeof(Holder), typeof(Answer));
        var second = Write(typeof(Holder), typeof(Answer));

        Assert.Equal(first, second);
        Assert.DoesNotContain("\r", first);
        Assert.StartsWith("// Generated by tools/MoonwellEditor.BridgeTypes", first);
        Assert.EndsWith(";\n", first);
        Assert.False(first.EndsWith(";\n\n", StringComparison.Ordinal));
        Assert.True(
            first.IndexOf("export type Answer", StringComparison.Ordinal)
            < first.IndexOf("export type Holder", StringComparison.Ordinal));
    }

    [Fact]
    public void Commands_tells_events_and_codes()
    {
        var text = Write(new BridgeShape(
            [
                new CommandShape("ping", typeof(Empty), typeof(string), false, false),
                new CommandShape("open", typeof(Empty), typeof(Answer), true, false),
                new CommandShape("close", typeof(Empty), null, false, false),
                new CommandShape("write", typeof(Args), null, false, true),
            ],
            [new EventShape("changed", typeof(Answer))],
            typeof(SampleCode),
            []));

        var commands = text[text.IndexOf("export type Commands = {", StringComparison.Ordinal)..];
        commands = commands[..(commands.IndexOf("\n};", StringComparison.Ordinal) + 3)];
        Assert.Equal(
            "export type Commands = {\n"
            + "  close: { args: Empty; answer: null };\n"
            + "  open: { args: Empty; answer: Answer | null };\n"
            + "  ping: { args: Empty; answer: string };\n"
            + "};",
            commands);
        Assert.Contains("export type Tells = {\n  write: Args;\n};\n", text);
        Assert.Contains("export type Events = {\n  changed: Answer;\n};\n", text);
        Assert.Contains("export type ErrorCode = \"noMap\" | \"badRequest\";\n", text);
        Assert.Contains("export type Empty = Record<string, never>;\n", text);
    }

    [Fact]
    public void A_name_clash_fails()
    {
        var error = Assert.Throws<BridgeTypesException>(() => Write(typeof(Clash)));

        Assert.Contains("MoonwellEditor.BridgeTypes.Tests.First.Thing", error.Message);
        Assert.Contains("MoonwellEditor.BridgeTypes.Tests.Second.Thing", error.Message);
    }

    [Fact]
    public void A_type_it_cannot_map_fails_with_the_path()
    {
        var error = Assert.Throws<BridgeTypesException>(() => Write(typeof(Loose)));

        Assert.Contains("Loose.payload", error.Message);
    }

    [Fact]
    public void A_type_written_both_ways_differently_fails()
    {
        var error = Assert.Throws<BridgeTypesException>(() =>
            Write(WithCommands(new CommandShape("set", typeof(Both), typeof(Both), false, false))));

        Assert.Contains("Both", error.Message);
    }

    [Fact]
    public void A_recursive_type_is_written_once()
    {
        var text = Write(typeof(Recursive));

        Assert.Equal(2, text.Split("export type Recursive = {").Length);
        Assert.Contains("  child: Recursive | null;\n", text);
    }
}
